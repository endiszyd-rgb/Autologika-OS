// Isolated data only. Exercises actual React controls and persisted calculation.
const {app}=require('electron')
const fs=require('node:fs'),path=require('node:path'),os=require('node:os'),assert=require('node:assert/strict')
app.setPath('userData',fs.mkdtempSync(path.join(os.tmpdir(),'autologika-estimate-')))
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms)),errors=[]
setTimeout(()=>app.exit(1),60000).unref()
app.on('browser-window-created',(_,win)=>{
 win.webContents.on('console-message',(_,level,message)=>{if(level>=3)errors.push(message)})
 win.webContents.once('did-finish-load',async()=>{try{
  const js=code=>win.webContents.executeJavaScript(code)
  const wait=async selector=>{for(let i=0;i<80;i++){if(await js(`!!document.querySelector(${JSON.stringify(selector)})`))return;await delay(100)}throw new Error(`Missing ${selector}`)}
  await wait('nav button[title="Centrum zlecenia"]')
  await js(`document.querySelector('nav button[title="Centrum zlecenia"]').click()`)
  await wait('.centerTabs')
  await js(`document.querySelector('.orderTabPrimary button:nth-child(2)').click()`)
  await wait('[data-order-tab="works"]')
  await js(`document.querySelector('[data-order-tab="works"]').click()`)
  await wait('.repairAddButton')
  await js(`document.querySelector('.repairAddButton').click()`)
  await wait('.workCascade fieldset')
  await delay(250)
  assert.equal(await js(`document.querySelector('.workCascade .actionrow.right .primary').disabled`),true)
  // Empty pricing cannot use a bundled example. Configure workshop settings.
  await js(`document.querySelector('.modalhead button').click();window.autologika.settings.setCatalogOverride('__repair_pricing_v1',{hourlyRate:200,corrosionMultiplier:1.25,accessMultiplier:1.2})`)
  await js(`document.querySelector('.repairAddButton').click()`)
  await wait('.workCascade fieldset')
  await delay(250)
  await js(`{const input=document.querySelector('.workCascade fieldset input[type=number]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'2');input.dispatchEvent(new Event('input',{bubbles:true}))}`)
  await delay(100)
  await js(`{const boxes=document.querySelectorAll('.workCascade fieldset input[type=checkbox]');boxes[0].click();boxes[1].click();boxes[3].click()}`)
  await delay(150)
  assert.equal(await js(`document.querySelector('.workCascade .actionrow.right .primary').disabled`),false)
  assert.equal(await js(`document.querySelector('.workCascade fieldset strong').textContent`),'600.00 zł')
  fs.mkdirSync(path.join(__dirname,'../artifacts/ui'),{recursive:true})
  fs.writeFileSync(path.join(__dirname,'../artifacts/ui/estimate-calculator.png'),(await win.webContents.capturePage()).toPNG())
  await js(`document.querySelector('.workCascade .actionrow.right .primary').click()`)
  await delay(700)
  const db=require('../electron/db.cjs').getDb(),item=db.prepare("SELECT * FROM order_items WHERE kind='ROBOCIZNA' ORDER BY id DESC LIMIT 1").get()
  assert.equal(item.qty*item.unit_price,600)
  assert.match(item.technical_description,/korozja 1.25/)
  assert.match(item.technical_description,/nie norma/)
  const repair=db.prepare('SELECT * FROM order_repair_operations WHERE id=?').get(item.repair_operation_id)
  assert.equal(repair.planned_hours*repair.labor_rate,600)
  assert.equal(errors.length,0,errors.join('\n'))
  console.log('ESTIMATE_UI_OK: configured multipliers, explicit time confirmation, persisted billing = 600; no renderer errors')
  app.exit(0)
 }catch(e){console.error(e,errors);app.exit(1)}})
})
app.whenReady().then(()=>{
 const db=require('../electron/db.cjs').getDb()
 const customer=db.prepare("INSERT INTO customers(name) VALUES ('Test')").run().lastInsertRowid
 const vehicle=db.prepare("INSERT INTO vehicles(customer_id,plate,make,model) VALUES (?,'TEST','Toyota','Corolla')").run(customer).lastInsertRowid
 db.prepare("INSERT INTO orders(vehicle_id,title,status) VALUES (?,'Test wyceny','NAPRAWA')").run(vehicle)
})
require('../electron/main.cjs')
