const fs = require('fs')
const path = require('path')
const zlib = require('zlib')

const root = path.resolve(__dirname, '..')
const functionDir = path.join(root, 'supabase', 'functions', 'approval')

function encodedFont(fileName) {
  const bytes = fs.readFileSync(path.join(functionDir, 'assets', fileName))
  const base64 = zlib.gzipSync(bytes, { level: 9 }).toString('base64')
  return base64.match(/.{1,120}/g).map((line) => `  '${line}'`).join(',\n')
}

const output = `// Generated by scripts/embed-approval-fonts.cjs. Do not edit manually.\n` +
`const regularGzip = [\n${encodedFont('NotoSans-Regular.ttf')}\n].join('')\n` +
`const boldGzip = [\n${encodedFont('NotoSans-Bold.ttf')}\n].join('')\n\n` +
`async function inflateFont(value: string) {\n` +
`  const compressed = Uint8Array.from(atob(value), character => character.charCodeAt(0))\n` +
`  const stream = new Response(compressed).body!.pipeThrough(new DecompressionStream('gzip'))\n` +
`  return new Uint8Array(await new Response(stream).arrayBuffer())\n` +
`}\n\n` +
`let cachedFonts: Promise<[Uint8Array, Uint8Array]> | null = null\n` +
`export function loadApprovalFonts() {\n` +
`  cachedFonts ||= Promise.all([inflateFont(regularGzip), inflateFont(boldGzip)])\n` +
`  return cachedFonts\n` +
`}\n`

fs.writeFileSync(path.join(functionDir, 'fonts.generated.ts'), output, 'utf8')
console.log('Embedded approval fonts:', Buffer.byteLength(output), 'bytes')
